package cli

import (
	"errors"
	"fmt"
	"io/fs"
	"os"
	"path/filepath"
	"slices"
	"sort"
	"strings"

	"github.com/spf13/cobra"

	"github.com/ugurboz/openchef/internal/config"
)

// Errors returned by `openchef init`.
var (
	ErrConfigExists     = errors.New("configuration already exists")
	ErrNoUsableRuntimes = errors.New("no usable agent CLI found")
)

const configHeader = `# OpenChef configuration, generated by "openchef init".
# Reference: docs/architecture.md §7.4 (model selection) and §13 (configuration).
#
# plan_tier drives the automatic effort profile: entry plans (free, pro, plus) start at
# "economy", large plans (max, ultra) at "balanced". Change it if your plan differs.

`

func newInitCommand(deps Deps) *cobra.Command {
	var (
		force  bool
		dryRun bool
		plans  map[string]string
	)
	cmd := &cobra.Command{
		Use:   "init",
		Short: "Detect installed agent CLIs and write ~/.openchef/config.toml",
		Long: "init detects claude, codex and agy, and writes a configuration with one pool " +
			"per subscription and sensible agents and routing for the CLIs that are usable. " +
			"Use --plan to record your subscription tier, e.g. --plan claude=max.",
		Example: "  openchef init\n  openchef init --plan claude=max --plan codex=pro\n  openchef init --dry-run",
		Args:    cobra.NoArgs,
		RunE: func(cmd *cobra.Command, _ []string) error {
			if err := validatePlanFlags(plans); err != nil {
				return err
			}
			paths, err := deps.Paths()
			if err != nil {
				return fmt.Errorf("resolve paths: %w", err)
			}

			var usable, skipped []string
			for _, st := range deps.Detector.Detect(cmd.Context()) {
				if st.Usable() {
					usable = append(usable, st.Runtime)
				} else {
					skipped = append(skipped, fmt.Sprintf("%s (%s)", st.Runtime, runtimeState(st)))
				}
			}
			if len(usable) == 0 {
				return fmt.Errorf("%w: install and log in to at least one of claude, codex or agy, then run `openchef doctor`", ErrNoUsableRuntimes)
			}

			cfg := config.Default(usable, plans)
			body, err := cfg.Marshal()
			if err != nil {
				return err
			}
			content := append([]byte(configHeader), body...)
			if _, err := config.Parse(content); err != nil {
				return fmt.Errorf("generated configuration is invalid (bug): %w", err)
			}

			p := printer{w: cmd.OutOrStdout()}
			if dryRun {
				p.printf("%s", content)
				return p.err
			}
			if err := writeConfig(paths, content, force); err != nil {
				return err
			}
			p.printf("Wrote %s\n", paths.Config)
			p.printf("Runtimes: %s\n", strings.Join(usable, ", "))
			for _, s := range skipped {
				p.printf("Skipped:  %s\n", s)
			}
			p.printf("Plans:    %s\n", describePlans(cfg))
			p.printf("Next:     openchef doctor\n")
			return p.err
		},
	}
	cmd.Flags().BoolVar(&force, "force", false, "overwrite an existing configuration")
	cmd.Flags().BoolVar(&dryRun, "dry-run", false, "print the configuration instead of writing it")
	cmd.Flags().StringToStringVar(&plans, "plan", nil, "subscription tier per runtime, e.g. claude=max (repeatable)")
	return cmd
}

func validatePlanFlags(plans map[string]string) error {
	for rt, tier := range plans {
		if !slices.Contains(config.Runtimes, rt) {
			return fmt.Errorf("--plan %s=%s: unknown runtime %q (want one of %s)", rt, tier, rt, strings.Join(config.Runtimes, ", "))
		}
		if !slices.Contains(config.PlanTiers, tier) {
			return fmt.Errorf("--plan %s=%s: unknown plan tier %q (want one of %s)", rt, tier, tier, strings.Join(config.PlanTiers, ", "))
		}
	}
	return nil
}

func writeConfig(paths config.Paths, content []byte, force bool) error {
	if err := os.MkdirAll(paths.Home, 0o700); err != nil {
		return fmt.Errorf("create %s: %w", paths.Home, err)
	}
	flags := os.O_WRONLY | os.O_CREATE | os.O_EXCL
	if force {
		flags = os.O_WRONLY | os.O_CREATE | os.O_TRUNC
	}
	f, err := os.OpenFile(paths.Config, flags, 0o600)
	if errors.Is(err, fs.ErrExist) {
		return fmt.Errorf("%w at %s (use --force to overwrite, or --dry-run to preview)", ErrConfigExists, paths.Config)
	}
	if err != nil {
		return fmt.Errorf("create %s: %w", paths.Config, err)
	}
	if _, err := f.Write(content); err != nil {
		_ = f.Close() // the write error is the one worth reporting
		return fmt.Errorf("write %s: %w", filepath.Base(paths.Config), err)
	}
	if err := f.Close(); err != nil {
		return fmt.Errorf("close %s: %w", paths.Config, err)
	}
	return nil
}

func describePlans(cfg *config.Config) string {
	names := make([]string, 0, len(cfg.Pools))
	for name := range cfg.Pools {
		names = append(names, name)
	}
	sort.Strings(names)
	parts := make([]string, 0, len(names))
	for _, n := range names {
		parts = append(parts, n+"="+cfg.Pools[n].PlanTier)
	}
	return strings.Join(parts, ", ") + " (change with --plan or by editing the file)"
}
